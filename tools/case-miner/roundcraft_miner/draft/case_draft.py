def build_case(candidate: dict[str, Any], *, case_id: str | None = None) -> dict[str, Any]:
    cid = make_case_id(candidate, case_id)
    ids = derived_ids(cid)
    f = extract_features(candidate)
    sit = SITUATIONS[f.situation]
    main = compute_main_prior(sit, f)
    evidence = choose_evidence(sit, f)
    actions_ordered = order_actions(main.actions, candidate["candidateId"])

    brief, brief_issues = build_brief(candidate, f, sit, ids, main, evidence, actions_ordered)
    followup, matrix, cls_key, cls_text, followup_issues = build_followup(
        candidate, f, sit, ids, main, {fact["id"] for fact in brief["facts"]})
    reveal, reveal_issues = build_reveal(candidate, f, sit, ids, main, evidence, matrix, cls_key)
    rubric = build_rubric(sit, ids, main, brief, evidence, matrix, followup)

    issues: list[str] = [scrub(str(note)) for note in candidate.get("reviewNotes") or []]
    issues += brief_issues + followup_issues + reveal_issues
    issues.append(FOLLOWUP_MATRIX_ISSUE)
    issues += [
        "The option set (actions, qualifiers, follow-up responses) is a template for this situation family, not derived from the demo; "
        "a reviewer must confirm every option is playable on this map at this moment and that no defensible line is missing.",
        "The debrief reasoning (whyItWorks, cost, assumption, breaksWhen, strongestAlternative, counterfactual, evidence explanations, "
        "principle) is templated per situation family and needs human tactical review.",
        "Rubric ratings, evidence points and follow-up qualities are heuristic priors (see editorial.notes), not tactical judgements; "
        "time thresholds (defuse duration + 7 s, 25 s comfortable) are unreviewed assumptions.",
        "The reveal continuation is machine-rendered from demo events; check it against the demo before any review.",
        f"publicMetadata.case_number ({PLACEHOLDER_CASE_NUMBER}) and edition_date_utc ({PLACEHOLDER_EDITION_DATE}) are placeholders to set at scheduling.",
        "editorial.references cannot carry a demo_source kind (the editorial schema allows only background_reading or source); "
        "the demo source is recorded as kind 'source' with a structured detail string.",
    ]
    if len(main.actions) and sum(1 for a in main.actions if a.best_quality >= 70) < 2:
        issues.append("Under the proposed priors only one action reaches a defensible line (>= 70); the decision may not be a real dilemma here.")
    issues.extend(f"Prior normalisation: {line}" for line in main.normalised)

    case: dict[str, Any] = {
        "caseId": cid,
        "origin": "synthetic",
        "editorial": None,  # filled after the disclosure pass so knownIssues can mention adjustments
        "edition": {
            "editionId": ids["editionId"],
            "releaseAt": None,
            "officialEndAt": None,
            "graceEndAt": None,
            "publicMetadata": {
                "case_number": PLACEHOLDER_CASE_NUMBER,
                "edition_date_utc": PLACEHOLDER_EDITION_DATE,
                "estimated_minutes": 6,
                "focus": focus_for(sit, f),
                "origin_label": ORIGIN_LABEL,
            },
        },
        "brief": brief,
        "followup": followup,
        "reveal": reveal,
        "rubric": rubric,
    }
    adjusted = _enforce_no_overlap(case)
    if adjusted:
        issues.append("Wording of these follow-up/reveal fields was auto-adjusted to avoid a 6-word overlap with the brief; "
                      "review for readability: " + ", ".join(adjusted))
    case["editorial"] = build_editorial(candidate, f, sit, ids, main, evidence, matrix, cls_text, issues)
    # Re-order keys so the file reads editorial-first like the existing cases.
    return {key: case[key] for key in ("caseId", "origin", "editorial", "edition", "brief", "followup", "reveal", "rubric")}


def player_facing_text(case: dict[str, Any]) -> list[str]:
    """Every string a player can see (brief, follow-up, reveal, public metadata)."""
    texts: list[str] = []
    for section in ("brief", "followup", "reveal"):
        texts += [text for _, _, text in _walk_prose(case[section])]
    texts += [str(v) for v in case["edition"]["publicMetadata"].values()]
    return texts


def identity_leaks(case: dict[str, Any]) -> list[str]:
    return [text for text in player_facing_text(case) if has_identity(text)]


