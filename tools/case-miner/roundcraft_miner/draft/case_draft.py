def build_rubric(sit: Situation, ids: dict[str, str], main: MainPrior, brief: dict[str, Any],
                 evidence: list[Signal], matrix: FollowupMatrix, followup: dict[str, Any]) -> dict[str, Any]:
    by_id = {a.template.id: a for a in main.actions}
    dim_ids = [d for d, _ in sit.dims]
    main_cells: list[dict[str, Any]] = []
    evidence_cells: list[dict[str, Any]] = []
    for action in brief["actions"]:
        prior = by_id[action["id"]]
        quals = {q.id: q for q in prior.qualifiers}
        for qid in action["qualifierIds"]:
            q = quals[qid]
            main_cells.append({"actionId": action["id"], "qualifierId": qid,
                               "ratings": {dim_ids[0]: q.ratings[0], dim_ids[1]: q.ratings[1]},
                               "caps": sorted(prior.caps)[:1] if prior.caps else []})
        points = evidence_points(sit, prior.template, evidence)
        for (a, b), pts in sorted(points.items()):
            evidence_cells.append({"actionId": action["id"], "evidenceIds": [a, b], "points": pts})
    return {
        "schemaVersion": 2,
        "caseRevision": ids["revision"],
        "rubricRevision": ids["rubricRevision"],
        "dimensions": [{"id": d, "weight": w} for d, w in sit.dims],
        "main": main_cells,
        "evidence": evidence_cells,
        "followup": {"type": "new_information",
                     "responses": [{"actionId": action["id"], "responseId": response["id"],
                                    "quality": matrix.cells[(action["id"], response["id"].removeprefix("now_"))]}
                                   for action in brief["actions"] for response in followup["responses"]]},
    }


# ---------------------------------------------------------------------------
# Disclosure self-check (mirror of the validator's 6-word overlap rule)
# ---------------------------------------------------------------------------

_NON_PROSE_KEYS = {"evidenceId", "kind", "timestamp", "caseRevision", "schemaVersion", "editionId", "id"}


def _brief_texts(brief: dict[str, Any]) -> list[str]:
    texts = [brief["title"], brief["focus"]]
    for key in ("facts", "actions", "qualifiers", "evidence", "confidence"):
        for item in brief[key]:
            texts.append(item["text"] if key == "facts" else item["label"])
    return texts


def _walk_prose(node: Any, path: str = ""):
    """Yield (container, key, text) for every prose string, skipping the validator's non-prose keys."""
    if isinstance(node, dict):
        for key, value in node.items():
            if key in _NON_PROSE_KEYS:
                continue
            if isinstance(value, str):
                yield node, key, value
            else:
                yield from _walk_prose(value, f"{path}.{key}")
    elif isinstance(node, list):
        for index, value in enumerate(node):
            if isinstance(value, str):
                yield node, index, value
            else:
                yield from _walk_prose(value, f"{path}[{index}]")


def brief_shingle_set(brief: dict[str, Any]) -> set[str]:
    return {gram for text in _brief_texts(brief) for gram in shingles(text)}


def disclosure_overlaps(case: dict[str, Any]) -> list[str]:
    """Fields of the follow-up/reveal that share a 6-word sequence with the brief (empty = passes)."""
    banned = brief_shingle_set(case["brief"])
    leaks = []
    for section in ("followup", "reveal"):
        for container, key, text in _walk_prose(case[section]):
            hit = next((g for g in shingles(text) if g in banned), None)
            if hit:
                leaks.append(f"{section}.{key}: {hit}")
    return leaks


def _enforce_no_overlap(case: dict[str, Any]) -> list[str]:
    banned = brief_shingle_set(case["brief"])
    adjusted: list[str] = []
    for section in ("followup", "reveal"):
        for container, key, text in list(_walk_prose(case[section])):
            new, changed = break_overlap(text, banned)
            if changed:
                container[key] = new
                adjusted.append(f"{section}.{key}")
    return adjusted


