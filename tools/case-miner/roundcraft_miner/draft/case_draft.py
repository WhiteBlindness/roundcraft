def make_case_id(candidate: dict[str, Any], case_id: str | None = None) -> str:
    if case_id:
        cid = slug(case_id, max_len=CASE_ID_MAX)
        if cid != case_id:
            raise ValueError(f"case id {case_id!r} must match ^[a-z0-9_]+$ (max {CASE_ID_MAX} chars)")
        return cid
    short = slug(str(candidate["candidateId"]).removeprefix("cand_"), max_len=8)[:6]
    category = slug(candidate.get("category", "case"), max_len=28)
    return f"case_{map_slug(candidate.get('map', 'map'))}_{category}_{short}"[:CASE_ID_MAX].rstrip("_")


def derived_ids(case_id: str) -> dict[str, str]:
    stem = case_id.removeprefix("case_")
    return {"revision": f"cr_{stem}", "rubricRevision": f"rr_{stem}", "editionId": f"ed_{stem}"}


def _ident(text: str, taken: set[str], fallback: str) -> str:
    base = slug(text, max_len=60) if text else fallback
    candidate, n = base, 2
    while candidate in taken:
        candidate = f"{base}_{n}"
        n += 1
    taken.add(candidate)
    return candidate


