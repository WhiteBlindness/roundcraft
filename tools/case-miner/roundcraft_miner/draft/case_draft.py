_FACT_CLASS_KEYWORDS: tuple[tuple[int, tuple[str, ...]], ...] = (
    (0, ("clock", "timer", "bomb", "time")),
    (1, ("alive", "players", "head")),
    (2, ("utility", "smoke", "flash", "grenade", "molotov", "he_")),
    (3, ("seen", "spotted", "sight", "heard")),
    (4, ("unknown", "unaccounted", "hidden")),
)


def _fact_class(fact: dict[str, Any]) -> int:
    hay = f"{fact.get('id', '')} {fact.get('text', '')}".lower()
    for cls, words in _FACT_CLASS_KEYWORDS:
        if any(word in hay for word in words):
            return cls
    if fact.get("status") in ("last_seen", "confirmed"):
        return 3
    return 5


def _plural(n: int, word: str, plural: str | None = None) -> str:
    return f"{n} {word}" if n == 1 else f"{n} {plural or word + 's'}"


def _utility_sentence(f: Features) -> str | None:
    parts = []
    for kind, one, many in (("smoke", "smoke", "smokes"), ("flash", "flash", "flashes"),
                            ("he", "HE grenade", "HE grenades"), ("molotov", "molotov", "molotovs"),
                            ("decoy", "decoy", "decoys")):
        count = f.util.get(kind, 0)
        if count:
            parts.append(_plural(count, one, many))
    if not parts:
        return None
    joined = parts[0] if len(parts) == 1 else ", ".join(parts[:-1]) + " and " + parts[-1]
    return f"Your team still holds {joined}."


def build_facts(candidate: dict[str, Any], f: Features) -> tuple[list[dict[str, str]], list[str]]:
    issues: list[str] = []
    view = candidate["playerKnown"]
    taken: set[str] = set()
    mined: list[tuple[int, int, dict[str, str]]] = []
    for index, raw in enumerate(view.get("facts") or []):
        status = raw.get("status")
        if status not in FACT_STATUSES:
            issues.append(f"Mined fact {raw.get('id')!r} had an unrecognised status {status!r}; treated as 'unknown'.")
            status = "unknown"
        text = fix_weapon_articles(scrub(str(raw.get("text", "")).strip()))
        basis = re.sub(r"\brounds? \d+(?:, \d+)*", "recent rounds", scrub(str(raw.get("basis", "")).strip()))
        if status == "inferred" and basis and "basis" not in text.lower() and len(text) + len(basis) < 470:
            text = f"{text.rstrip('.')}. Basis: {basis.rstrip('.')}."
        if not text:
            continue
        mined.append((_fact_class(raw), index, {"id": _ident(str(raw.get("id", "")), taken, f"fact_{index + 1}"),
                                                "status": status, "text": truncate(text, 500)}))
        if status == "last_seen" and not any(ch.isdigit() for ch in text) and "ago" not in text.lower():
            issues.append(f"Fact {mined[-1][2]['id']!r} is last_seen but its text states no age.")

    derived: list[tuple[int, dict[str, str]]] = []
    classes = {cls for cls, _, _ in mined}
    perspective_fact = {"id": _ident("perspective", taken, "perspective"), "status": "confirmed",
                        "text": f"You play the {f.perspective} side on {map_display(f.map_name)}."}
    if 0 not in classes and f.time_left is not None:
        if f.time_kind == "bomb":
            site = f" on site {f.bomb_site}" if f.bomb_site else ""
            text = f"The bomb is planted{site}. About {seconds_phrase(f.time_left)} are left before it explodes."
            fid = "bomb_timer"
        else:
            text = f"About {seconds_phrase(f.time_left)} are left on the round clock."
            fid = "round_clock"
        derived.append((0, {"id": _ident(fid, taken, fid), "status": "confirmed", "text": text}))
    if 1 not in classes:
        derived.append((1, {"id": _ident("alive_count", taken, "alive_count"), "status": "confirmed",
                            "text": f"Your team has {f.own_alive} players alive and the opposing team has {f.enemy_alive}."}))
    if 2 not in classes:
        sentence = _utility_sentence(f)
        if sentence:
            derived.append((2, {"id": _ident("own_utility", taken, "own_utility"), "status": "confirmed", "text": sentence}))
    if f.perspective == "CT" and f.own_alive > 0:
        # Kits are visible on the scoreboard to teammates, so this is known to the deciding team.
        kit_text = ("No one on your team carries a defuse kit." if f.own_kit == 0 else
                    f"{f.own_kit} of your {f.own_alive} alive players {'carries' if f.own_kit == 1 else 'carry'} a defuse kit.")
        derived.append((2, {"id": _ident("defuse_kits", taken, "defuse_kits"), "status": "confirmed", "text": kit_text}))
    if 4 not in classes and f.unknown_enemies > 0 and not any(m[2]["status"] == "unknown" for m in mined):
        derived.append((4, {"id": _ident("unknown_positions", taken, "unknown_positions"), "status": "unknown",
                            "text": f"{_plural(f.unknown_enemies, f.enemy_noun)} cannot currently be placed."}))

    # mined facts keep their source order inside a class; derived facts sort ahead of mined ones of the same class
    keyed = [(cls, 0, i, fact) for i, (cls, fact) in enumerate(derived)] + [(cls, 1, idx, fact) for cls, idx, fact in mined]
    facts = [perspective_fact] + [item[3] for item in sorted(keyed, key=lambda item: item[:3])]
    if len(facts) > MAX_FACTS:
        issues.append(f"Brief facts were capped at {MAX_FACTS} by priority (clock/bomb, alive counts, utility, sightings, unknowns); "
                      f"{len(facts) - MAX_FACTS} lower-priority fact(s) were dropped.")
        facts = facts[:MAX_FACTS]
    if not any(fact["status"] in ("inferred", "unknown") for fact in facts):
        issues.append("No fact is marked inferred or unknown; the brief presents nothing as uncertain.")
    return facts, issues


def specific_title(sit: Situation, f: Features) -> str:
    """A title that names the actual situation, e.g. '2v2 retake at A on Mirage'."""
    game = f"{f.own_alive}v{f.enemy_alive}"
    where = map_display(f.map_name)
    site = f" at {f.bomb_site}" if f.bomb_site else ""
    seconds = f"{f.time_left:.0f} s" if f.time_left is not None else None
    if sit.id == "retake":
        return f"{game} retake{site} on {where}"
    if sit.id == "post_plant_hold":
        return f"{game} post-plant{site} on {where}"
    if sit.id == "execute_or_default" and seconds and f.time_left is not None and f.time_left <= 20:
        return f"Plant or save: {game} with {seconds} left on {where}"
    if sit.id == "execute_or_default" and seconds:
        ground = " and the bomb on the ground" if f.bomb_status == "dropped" else " and no plant"
        return f"{game} with {seconds} left{ground} on {where}"
    if sit.id == "execute_or_default":
        return f"{game} mid-round read as the attackers on {where}"
    if sit.id == "hold_or_rotate":
        return f"{game} hold or rotate as the defenders on {where}"
    return sit.title.format(map=where)


FOCUS_MAX = 80  # publicMetadata.focus limit


def focus_for(sit: Situation, f: Features) -> str:
    """A focus line that matches the situation actually presented (variants of the family default)."""
    late = f.time_left is not None
    if sit.id == "execute_or_default" and late and f.time <= 20:
        focus = "Trying to plant with the clock nearly gone versus saving the weapons"
    elif sit.id == "execute_or_default" and late and f.time <= 45:
        focus = "Committing to a plant with the round clock running short"
    elif sit.id == "retake" and f.time < f.t_low:
        focus = "Whether a retake can still finish before the bomb explodes"
    elif sit.id == "post_plant_hold" and f.time < 12:
        focus = "Staying out of contact while the bomb timer runs out"
    else:
        focus = sit.focus
    return truncate(focus, FOCUS_MAX)


def build_brief(candidate: dict[str, Any], f: Features, sit: Situation, ids: dict[str, str],
                main: MainPrior, evidence: list[Signal], actions_ordered: list[ActionPrior]) -> tuple[dict[str, Any], list[str]]:
    facts, issues = build_facts(candidate, f)
    qualifiers: list[dict[str, str]] = []
    actions: list[dict[str, Any]] = []
    for action in actions_ordered:
        quals = order_qualifiers(action.qualifiers, candidate["candidateId"], action.template.id)
        for q in quals:
            qualifiers.append({"id": q.id, "label": q.label})
        actions.append({"id": action.template.id, "label": truncate(scrub(action.label), 120),
                        "qualifierIds": [q.id for q in quals]})
    brief = {
        "schemaVersion": 1,
        "editionId": ids["editionId"],
        "caseRevision": ids["revision"],
        "title": specific_title(sit, f),
        "focus": focus_for(sit, f),
        "origin": "synthetic",
        "facts": facts,
        "actions": actions,
        "qualifiers": qualifiers,
        "evidence": [{"id": s.id, "label": scrub(s.label)} for s in evidence],
        "confidence": [dict(c) for c in CONFIDENCE],
    }
    return brief, issues


