def _read_manifest(source_id: str) -> dict[str, Any] | None:
    try:
        path = paths.manifests_dir() / f"{source_id}.json"
        return read_json(path) if path.exists() else None
    except Exception:  # noqa: BLE001 - provenance lookup is best effort
        return None


def demo_sha256(candidate: dict[str, Any], manifest: dict[str, Any] | None) -> str:
    for source in (candidate, candidate.get("groundTruth") or {}):
        value = source.get("demoSha256")
        if value:
            return str(value)
    if manifest and manifest.get("demo", {}).get("sha256"):
        return str(manifest["demo"]["sha256"])
    try:  # the parsed match carries the demo hash too
        match_path = paths.parsed_dir(candidate["sourceId"]) / "match.json"
        if match_path.exists():
            return str(read_json(match_path).get("demoSha256", "unknown"))
    except Exception:  # noqa: BLE001
        pass
    return "unknown"


def build_editorial(candidate: dict[str, Any], f: Features, sit: Situation, ids: dict[str, str], main: MainPrior,
                    evidence: list[Signal], matrix: FollowupMatrix, cls_text: str, issues: list[str]) -> dict[str, Any]:
    manifest = _read_manifest(candidate["sourceId"])
    sha = demo_sha256(candidate, manifest)
    embedded = (candidate.get("groundTruth") or {}).get("source") or {}
    lane = (manifest or {}).get("rights", {}).get("contentLane") or embedded.get("contentLane") or "unknown (manifest not found)"
    reference = {
        "label": "Demo source (demo_source)",
        "detail": (
            f"kind=demo_source; sourceId={candidate['sourceId']}; candidateId={candidate['candidateId']}; "
            f"map={candidate.get('map')}; round={candidate.get('round')}; decisionTick={candidate.get('decisionTick')}; "
            f"decisionT={candidate.get('decisionT')}s; perspective={candidate.get('perspective')}; "
            f"category={candidate.get('category')}; demoSha256={sha}"
        ),
        "kind": "source",
    }
    score = candidate.get("score") or {}
    notes = [
        PROPOSED_RUBRIC_NOTE,
        "",
        "LANE: demo-grounded SYNTHETIC. The situation is inspired by a decision point in a real demo (see references) but the case "
        "does not claim to reproduce the match and contains no player names, Steam IDs, team names or player ids. "
        f"Content lane recorded on the source manifest: {lane}.",
        "The brief, evidence and actions use only candidate.playerKnown (plus map, perspective and category). The follow-up uses only "
        "candidate.followUp. Ground truth and the actual line appear only in the reveal. The historical line is shown for comparison "
        "and is NOT treated as the correct answer.",
        f"Candidate: {candidate['candidateId']} (score {score.get('total')}, category {candidate.get('category')}, "
        f"template family {sit.id}). Summary: {scrub(str(candidate.get('summary', '')))}",
        "",
        "PRIOR TABLE (every rubric value below is derivable from these rules and the player-known features):",
        *main.explain,
        *(f"normalisation: {line}" for line in main.normalised),
        f"follow-up: {cls_text}",
        *(f"  {line}" for line in matrix.explain),
        *(f"  locked {locked} -> " + ", ".join(f"{now}={matrix.cells[(locked, now)]}" for now in matrix.value_after)
          for locked in matrix.value_after),
        *(f"  {line}" for line in [
            f"evidence pairs: points = clamp(round(20 * (w_a + w_b) / (w_top1 + w_top2)), 3, 20) with per-signal weights from the "
            f"situation table and per-action overrides; signals: " + ", ".join(f"{s.id}({s.cls})" for s in evidence)]),
        f"Order of actions/qualifiers/responses is a deterministic hash of the candidate id; the top-ranked action is never first.",
    ]
    return {
        "status": "draft",
        "revision": ids["revision"],
        "rubricRevision": ids["rubricRevision"],
        "author": AUTHOR,
        "reviewers": [],
        "references": [reference],
        "knownIssues": issues,
        "notes": "\n".join(notes),
    }


