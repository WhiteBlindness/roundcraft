# --- independent re-implementations (do not import the module under test) ---------------------------


def _tokens(text: str) -> list[str]:
    text = unicodedata.normalize("NFKD", text.lower())
    return [t for t in re.split(r"[\W_]+", text) if t]


def _grams(text: str) -> set[str]:
    tokens = _tokens(text)
    return {" ".join(tokens[i : i + 6]) for i in range(len(tokens) - 5)}


NON_PROSE = {"evidenceId", "kind", "timestamp", "caseRevision", "schemaVersion", "editionId", "id"}


def _prose(node):
    if isinstance(node, str):
        yield node
    elif isinstance(node, list):
        for item in node:
            yield from _prose(item)
    elif isinstance(node, dict):
        for key, value in node.items():
            if key not in NON_PROSE:
                yield from _prose(value)


def _brief_text(brief: dict) -> list[str]:
    texts = [brief["title"], brief["focus"]]
    texts += [f["text"] for f in brief["facts"]]
    for key in ("actions", "qualifiers", "evidence", "confidence"):
        texts += [item["label"] for item in brief[key]]
    return texts


def _line_quality(rubric: dict, cell: dict) -> float:
    weights = {d["id"]: d["weight"] for d in rubric["dimensions"]}
    raw = sum(weights[d] * r for d, r in cell["ratings"].items())
    cap = min(cell["caps"]) if cell["caps"] else 100
    return min(raw, cap * 4) / 4


