def _real_candidates():
    from roundcraft_miner import paths

    root = paths.data_root() / "candidates"
    return sorted(root.glob("*/cand_*/candidate.json")) if root.exists() else []


@pytest.mark.skipif(not _real_candidates(), reason="no mined candidates under data-local/candidates")
def test_every_real_candidate_builds_a_clean_draft():
    banned_pid = PID
    seen_families = set()
    for path in _real_candidates():
        candidate = json.loads(path.read_text(encoding="utf-8"))
        case = build_case(candidate)
        banned = set().union(*(_grams(t) for t in _brief_text(case["brief"])))
        for section in ("followup", "reveal"):
            for text in _prose(case[section]):
                assert not (_grams(text) & banned), (path.parent.name, section, text)
        assert identity_leaks(case) == [], path.parent.name
        assert not banned_pid.search(json.dumps(case["brief"]) + json.dumps(case["followup"]) + json.dumps(case["reveal"]))
        assert len(case["brief"]["evidence"]) == 5 and 3 <= len(case["brief"]["actions"]) <= 5
        assert case["editorial"]["status"] == "draft"
        rubric = case["rubric"]
        best = max(_line_quality(rubric, c) for c in rubric["main"])
        assert best >= 90, (path.parent.name, best)
        seen_families.add((candidate["category"], candidate["perspective"]))
    assert seen_families
