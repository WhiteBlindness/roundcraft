def test_rubric_matrix_is_complete(candidate):
    case = build_case(candidate)
    brief, rubric, followup = case["brief"], case["rubric"], case["followup"]
    dims = {d["id"] for d in rubric["dimensions"]}
    assert sum(d["weight"] for d in rubric["dimensions"]) == 100
    cells = {(c["actionId"], c["qualifierId"]) for c in rubric["main"]}
    expected = {(a["id"], q) for a in brief["actions"] for q in a["qualifierIds"]}
    assert cells == expected and len(rubric["main"]) == len(expected)
    for cell in rubric["main"]:
        assert set(cell["ratings"]) == dims and all(isinstance(v, int) and 0 <= v <= 4 for v in cell["ratings"].values())
        assert len(cell["caps"]) <= 8 and all(0 <= c <= 100 for c in cell["caps"])
    evidence_ids = sorted(e["id"] for e in brief["evidence"])
    pairs = {tuple(p) for p in combinations(evidence_ids, 2)}
    assert len(pairs) == 10
    for action in brief["actions"]:
        rows = [tuple(sorted(c["evidenceIds"])) for c in rubric["evidence"] if c["actionId"] == action["id"]]
        assert len(rows) == 10 and set(rows) == pairs
    assert all(isinstance(c["points"], int) and 0 <= c["points"] <= 20 for c in rubric["evidence"])
    published = {r["id"] for r in followup["responses"]}
    assert rubric["followup"]["type"] == followup["type"] == "new_information"
    assert {r["responseId"] for r in rubric["followup"]["responses"]} == published
    qualities = [r["quality"] for r in rubric["followup"]["responses"]]
    assert all(isinstance(q, int) and 0 <= q <= 100 for q in qualities) and max(qualities) - min(qualities) >= 20


def test_rubric_reaches_best_supported_and_offers_alternatives(candidate):
    case = build_case(candidate)
    rubric = case["rubric"]
    by_action: dict[str, float] = {}
    for cell in rubric["main"]:
        by_action[cell["actionId"]] = max(by_action.get(cell["actionId"], 0), _line_quality(rubric, cell))
    assert max(by_action.values()) >= 90
    assert sum(1 for q in by_action.values() if q >= 70) >= 2


def test_best_action_is_not_always_first(retake, clone):
    positions = set()
    for index in range(60):
        variant = clone(retake)
        variant["candidateId"] = f"cand_{index:012x}"
        case = build_case(variant)
        rubric = case["rubric"]
        best: dict[str, float] = {}
        for cell in rubric["main"]:
            best[cell["actionId"]] = max(best.get(cell["actionId"], 0), _line_quality(rubric, cell))
        top = max(best.values())
        order = [a["id"] for a in case["brief"]["actions"]]
        leaders = [i for i, a in enumerate(order) if best[a] == top]
        assert leaders and 0 not in leaders  # the best-supported action is never listed first
        positions.add(leaders[0])
    assert len(positions) >= 2, "the best action should move around between candidates"


def test_best_followup_response_is_not_always_first(retake, clone):
    firsts = set()
